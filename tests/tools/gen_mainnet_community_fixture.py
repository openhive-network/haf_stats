#!/usr/bin/env python3
"""Regenerate tests/mainnet_community_fixture.sql from live mainnet data.

The community code path cannot be exercised against our replay: it is 2016 chain history
and communities did not exist until block 37,500,000. A full mainnet HAF would fix that,
but it is multi-TB and a multi-day replay.

This closes the gap a different way. Everything our resolver consumes for a comment is
(author, permlink, parent_author, parent_permlink) -- all of which condenser_api returns
for any post. And hivemind hands us the ANSWER for free in the same response: `category`
is the thread ROOT's community, propagated to every descendant. So we can pull real
threads, synthesize exactly the raw comment_operations they came from, run our real
processors over them, and assert our derived community equals hivemind's own verdict for
every node -- including the deep replies where the resolver has to walk the whole chain.

Network is needed only to REGENERATE; the generated .sql is committed, so CI stays offline.

Usage:  python3 tests/tools/gen_mainnet_community_fixture.py > tests/mainnet_community_fixture.sql
"""

import json
import re
import sys
import urllib.request

API = "https://api.hive.blog"
COMMUNITY_RE = re.compile(r"^hive-[1-3][0-9]{4,6}$")

# Accounts chosen for breadth: they post and reply across many communities, which yields
# several distinct communities plus legacy tag categories in one pull.
SEED_ACCOUNTS = ["blocktrades", "gtg", "arcange"]
SEED_LIMIT = 10

# Blocks live inside ONE 1200-block refresh bucket (31252 = 37,502,400..37,503,599) so
# process_content_stats' boundary hook never fires and the period rollups other tavern
# tests assert on are left alone. Starting at ...401 keeps (_first_block - 1) in the same
# bucket as _last_block, which is what the hook actually compares.
FIRST_BLOCK = 37502401
BLOCK_DAY = "2020-06-15 12:00:00"
FIRST_ACCOUNT_ID = 48000


def rpc(method, params):
    req = urllib.request.Request(
        API,
        data=json.dumps({"jsonrpc": "2.0", "method": method, "params": params, "id": 1}).encode(),
        headers={"Content-Type": "application/json"},
    )
    return json.loads(urllib.request.urlopen(req, timeout=30).read()).get("result")


def collect():
    seeds = []
    for acct in SEED_ACCOUNTS:
        for sort in ("comments", "posts"):
            for p in rpc("bridge.get_account_posts", {"sort": sort, "account": acct, "limit": SEED_LIMIT}) or []:
                seeds.append((p["author"], p["permlink"]))

    nodes, seen = {}, set()
    for author, permlink in seeds:
        # Walk up to the thread root so every node's parent is present in the fixture.
        while (author, permlink) not in seen:
            seen.add((author, permlink))
            c = rpc("condenser_api.get_content", [author, permlink])
            if not c or not c.get("author"):
                break
            nodes[(c["author"], c["permlink"])] = {
                "author": c["author"],
                "permlink": c["permlink"],
                "parent_author": c["parent_author"],
                "parent_permlink": c["parent_permlink"],
                "depth": c["depth"],
                "category": c["category"],
            }
            if c["parent_author"] == "":
                break
            author, permlink = c["parent_author"], c["parent_permlink"]

    # Drop any node whose parent failed to fetch: an orphan would look like a resolution
    # failure when it is really a gap in the sample.
    keys = set(nodes)
    while True:
        orphans = {
            k for k, n in nodes.items()
            if n["parent_author"] != "" and (n["parent_author"], n["parent_permlink"]) not in keys
        }
        if not orphans:
            break
        for k in orphans:
            del nodes[k]
        keys = set(nodes)
    return nodes


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    nodes = collect()
    if not nodes:
        sys.exit("no nodes collected")

    # Parents before children: a node's parent is always exactly one depth shallower and
    # is present (orphans were dropped above), so depth order is a valid topological order.
    ordered = sorted(nodes.values(), key=lambda n: (n["depth"], n["author"], n["permlink"]))
    communities = sorted({n["category"] for n in ordered if COMMUNITY_RE.match(n["category"])})
    accounts = sorted({n["author"] for n in ordered} | set(communities))
    ids = {name: FIRST_ACCOUNT_ID + i for i, name in enumerate(accounts)}

    # Community registrations first, then content in topological order.
    reg_blocks = {c: FIRST_BLOCK + i for i, c in enumerate(communities)}
    content_first = FIRST_BLOCK + len(communities)
    last_block = content_first + len(ordered) - 1

    out = []
    w = out.append
    w("-- GENERATED by tests/tools/gen_mainnet_community_fixture.py -- do not edit by hand.")
    w("--")
    w("-- Real mainnet threads, replayed as the raw comment_operations they came from, with")
    w("-- hivemind's own `category` per node as the expected answer. This is the only test")
    w("-- that exercises the community derivation against REAL data: our replay is 2016 chain")
    w("-- history and communities did not exist until block 37,500,000.")
    w("--")
    w(f"-- {len(ordered)} nodes, max depth {max(n['depth'] for n in ordered)}, "
      f"{len(communities)} communities + "
      f"{len({n['category'] for n in ordered}) - len(communities)} legacy tag categories.")
    w("-- Legacy categories are the negative case: they look like ordinary categories to us")
    w("-- and must resolve to NO community, exactly as hivemind reports them.")
    w("")
    w("INSERT INTO hafd.operation_types (id, name, is_virtual) VALUES")
    w("    (17, 'hive::protocol::delete_comment_operation', FALSE),")
    w("    (100, 'hive::protocol::account_created_operation', TRUE)")
    w("ON CONFLICT (id) DO NOTHING;")
    w("")
    w("INSERT INTO hafd.accounts (id, name) VALUES")
    w(",\n".join(f"    ({ids[a]}, {sql_str(a)})" for a in accounts))
    w("ON CONFLICT (id) DO NOTHING;")
    w("")
    w("-- Vesting mirrors the other fixtures so get_network_hp_distribution's ratio is unchanged.")
    w("INSERT INTO hafd.blocks (num, created_at, total_vesting_shares, total_vesting_fund_hive)")
    w(f"SELECT n, TIMESTAMP {sql_str(BLOCK_DAY)}, 1000000000, 1000000000")
    w(f"FROM GENERATE_SERIES({FIRST_BLOCK - 1}, {last_block}) AS n")
    w("ON CONFLICT (num) DO NOTHING;")
    w("")
    w("-- Register each community by creating its account, as hivemind does.")
    w("INSERT INTO hafd.operations (id, op_type_id, body_value)")
    w("SELECT * FROM (VALUES")
    rows = []
    for c in communities:
        rows.append(
            f"    (hafd.operation_id({reg_blocks[c]}, 1),\n"
            f"     (SELECT id FROM hafd.operation_types WHERE name = 'hive::protocol::account_created_operation'),\n"
            f"     JSONB_BUILD_OBJECT('new_account_name', {sql_str(c)}))"
        )
    w(",\n".join(rows))
    w(") AS v(id, op_type_id, body_value)")
    w("ON CONFLICT (id) DO NOTHING;")
    w("")
    w("-- Content, parents before children.")
    w("INSERT INTO hafd.operations (id, op_type_id, body_value) VALUES")
    rows = []
    for i, n in enumerate(ordered):
        rows.append(
            f"    (hafd.operation_id({content_first + i}, 1), 1, JSONB_BUILD_OBJECT(\n"
            f"        'author', {sql_str(n['author'])}, 'permlink', {sql_str(n['permlink'])},\n"
            f"        'parent_author', {sql_str(n['parent_author'])}, "
            f"'parent_permlink', {sql_str(n['parent_permlink'])}))"
        )
    w(",\n".join(rows))
    w("ON CONFLICT (id) DO NOTHING;")
    w("")
    w("-- hivemind's verdict per node: `category` is the thread ROOT's community, propagated")
    w("-- to every descendant. Our derivation must reproduce it from parent links alone.")
    w("-- haf_stats_test is created by the regression harness on a real node, but the stub")
    w("-- stack does not load that, so create it here too.")
    w("CREATE SCHEMA IF NOT EXISTS haf_stats_test;")
    w("")
    w("CREATE TABLE IF NOT EXISTS haf_stats_test.mainnet_community_expected (")
    w("    author TEXT NOT NULL,")
    w("    permlink TEXT NOT NULL,")
    w("    depth INT NOT NULL,")
    w("    hivemind_category TEXT NOT NULL,")
    w("    expected_community TEXT,")
    w("    PRIMARY KEY (author, permlink)")
    w(");")
    w("")
    w("INSERT INTO haf_stats_test.mainnet_community_expected")
    w("    (author, permlink, depth, hivemind_category, expected_community) VALUES")
    rows = []
    for n in ordered:
        expected = sql_str(n["category"]) if COMMUNITY_RE.match(n["category"]) else "NULL"
        rows.append(
            f"    ({sql_str(n['author'])}, {sql_str(n['permlink'])}, {n['depth']}, "
            f"{sql_str(n['category'])}, {expected})"
        )
    w(",\n".join(rows))
    w("ON CONFLICT (author, permlink) DO NOTHING;")
    w("")
    w("-- One batch spanning the whole sample, so most parent links are resolved IN-BATCH -")
    w("-- the case a plain comment_registry lookup gets wrong.")
    w(f"SELECT haf_stats_app.process_community_registry({FIRST_BLOCK}, {last_block});")
    w(f"SELECT haf_stats_app.process_content_stats({FIRST_BLOCK}, {last_block});")
    w("")
    w("DO $$")
    w("DECLARE")
    w("    _total INT;")
    w("    _wrong INT;")
    w("    _worst TEXT;")
    w("    _deep INT;")
    w("BEGIN")
    w("    SELECT COUNT(*) INTO _total FROM haf_stats_test.mainnet_community_expected;")
    w("")
    w("    SELECT COUNT(*), MAX(e.depth) INTO _wrong, _deep")
    w("    FROM haf_stats_test.mainnet_community_expected e")
    w("    JOIN hafd.accounts a ON a.name = e.author")
    w("    JOIN haf_stats_backend.comment_registry r")
    w("        ON r.author_id = a.id AND r.permlink = e.permlink")
    w("    WHERE r.community IS DISTINCT FROM e.expected_community;")
    w("")
    w("    IF _wrong <> 0 THEN")
    w("        SELECT FORMAT('%s/%s depth=%s ours=%s hivemind=%s',")
    w("                      e.author, e.permlink, e.depth,")
    w("                      COALESCE(r.community, '(none)'), e.hivemind_category)")
    w("        INTO _worst")
    w("        FROM haf_stats_test.mainnet_community_expected e")
    w("        JOIN hafd.accounts a ON a.name = e.author")
    w("        JOIN haf_stats_backend.comment_registry r")
    w("            ON r.author_id = a.id AND r.permlink = e.permlink")
    w("        WHERE r.community IS DISTINCT FROM e.expected_community")
    w("        ORDER BY e.depth DESC")
    w("        LIMIT 1;")
    w("")
    w("        RAISE EXCEPTION 'mainnet community parity: % of % real nodes resolved to a different community than hivemind reports (deepest disagreement: %)',")
    w("            _wrong, _total, _worst;")
    w("    END IF;")
    w("")
    w("    -- Guard the test itself: if the sample stopped containing deep replies or")
    w("    -- community content, it would pass while proving nothing.")
    w("    SELECT MAX(depth) INTO _deep FROM haf_stats_test.mainnet_community_expected;")
    w("    IF _deep < 3 THEN")
    w("        RAISE EXCEPTION 'mainnet community fixture is too shallow (max depth %); regenerate it - it is no longer testing multi-level root resolution', _deep;")
    w("    END IF;")
    w("")
    w("    IF NOT EXISTS (SELECT 1 FROM haf_stats_test.mainnet_community_expected WHERE expected_community IS NOT NULL)")
    w("       OR NOT EXISTS (SELECT 1 FROM haf_stats_test.mainnet_community_expected WHERE expected_community IS NULL) THEN")
    w("        RAISE EXCEPTION 'mainnet community fixture lost either its community or its legacy-category nodes; regenerate it';")
    w("    END IF;")
    w("")
    w("    RAISE NOTICE 'mainnet community parity OK: % real nodes (max depth %) resolved exactly as hivemind reports them.', _total, _deep;")
    w("END;")
    w("$$;")
    w("")
    w("-- ---------------------------------------------------------------------------")
    w("-- Mirror these same nodes into the hivemind_app test double, when one is present,")
    w("-- so tests/parity/community_vs_hivemind.sql runs over REAL communities, real")
    w("-- accounts and a real depth distribution rather than only the synthetic fixture.")
    w("-- Each node appears once on each side, so the oracle's expected excess is unchanged.")
    w("-- Guarded: this file is also useful on a node with no hivemind stub at all.")
    w("-- ---------------------------------------------------------------------------")
    w("DO $$")
    w("BEGIN")
    w("    IF TO_REGCLASS('hivemind_app.hive_posts') IS NULL THEN")
    w("        RAISE NOTICE 'mainnet community fixture: no hivemind_app on this node - skipping the oracle mirror.';")
    w("        RETURN;")
    w("    END IF;")
    w("")
    w("    INSERT INTO hivemind_app.hive_communities (id, type_id, name, title)")
    w("    SELECT c.id, SUBSTRING(c.name FROM 6 FOR 1)::SMALLINT, c.name, ''")
    w("    FROM (VALUES")
    w(",\n".join(f"        ({1000 + i}, {sql_str(c)})" for i, c in enumerate(communities)))
    w("    ) AS c(id, name)")
    w("    ON CONFLICT (id) DO NOTHING;")
    w("")
    w("    INSERT INTO hivemind_app.hive_accounts (id, name)")
    w("    SELECT a.id, a.name FROM (VALUES")
    w(",\n".join(f"        ({ids[a]}, {sql_str(a)})" for a in accounts))
    w("    ) AS a(id, name)")
    w("    ON CONFLICT (id) DO NOTHING;")
    w("")
    w("    INSERT INTO hivemind_app.hive_posts")
    w("        (id, author_id, community_id, depth, counter_deleted, created_at)")
    w("    SELECT p.id, p.author_id, p.community_id, p.depth, 0, TIMESTAMP " + sql_str(BLOCK_DAY))
    w("    FROM (VALUES")
    rows = []
    comm_ids = {c: 1000 + i for i, c in enumerate(communities)}
    for i, n in enumerate(ordered):
        cid = comm_ids.get(n["category"])
        rows.append(
            f"        ({2000 + i}, {ids[n['author']]}, "
            f"{cid if cid is not None else 'NULL'}, {n['depth']})"
        )
    w(",\n".join(rows))
    w("    ) AS p(id, author_id, community_id, depth)")
    w("    ON CONFLICT (id) DO NOTHING;")
    w("END;")
    w("$$;")
    w("")
    w("-- Record a processed head, so the stub looks like a node that actually replayed these")
    w("-- blocks. tests/parity/community_vs_hivemind.sql bounds hivemind's side by this head;")
    w("-- without it the oracle cannot tell 'behind' from 'wrong' and skips.")
    w("UPDATE haf_stats_app.app_status")
    w(f"SET last_processed_block = {last_block}")
    w(f"WHERE last_processed_block < {last_block};")
    w("")

    print("\n".join(out).rstrip("\n"))


if __name__ == "__main__":
    main()
